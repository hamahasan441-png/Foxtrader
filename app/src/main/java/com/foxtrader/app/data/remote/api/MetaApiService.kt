data class MetaApiCandleResponse(
    val symbol: String = "",
    val timeframe: String = "",
    /** ISO-8601 on the current historical market-data API. */
    val time: String = "",
    val open: Double = 0.0,
    val high: Double = 0.0,
    val low: Double = 0.0,
    val close: Double = 0.0,
    @SerialName("tickVolume") val tickVolume: Double = 0.0,
    val volume: Double = 0.0,
