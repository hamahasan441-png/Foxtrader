@Serializable
data class MetaApiSymbolSpecResponse(
    val symbol: String = "",
    @SerialName("tickSize") val tickSize: Double = 0.0,
    @SerialName("minVolume") val minVolume: Double = 0.0,
    @SerialName("maxVolume") val maxVolume: Double = 0.0,
    @SerialName("volumeStep") val volumeStep: Double = 0.0,
    @SerialName("contractSize") val contractSize: Double = 0.0,
    /** Broker-reported point size; distinct from tickSize on some instruments. */
    val point: Double = 0.0,
    /** Base currency from MetaApi symbol specification (e.g. EUR for EURUSD). */
    val baseCurrency: String = "",
    /** Profit/quote currency from MetaApi (e.g. USD for EURUSD). */
    val profitCurrency: String = "",
    val digits: Int = 5,
    val description: String = "",
    /** Minimum distance from current price to SL/TP/pending open price, in points. */
    val stopsLevel: Double = 0.0,
    /** Pending-order modification freeze distance, in points. */
    val freezeLevel: Double = 0.0,
    val allowedOrderTypes: List<String> = emptyList(),
    val allowedExpirationModes: List<String> = emptyList(),
)

